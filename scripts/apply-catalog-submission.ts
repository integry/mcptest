/**
 * Turns a `catalog-submission` repository_dispatch payload into a catalog entry
 * and, after runner-side validation, into the pull request body.
 *
 * The workflow (.github/workflows/catalog-submission.yml) calls it twice through
 * scripts/run-apply-catalog-submission.ts:
 *
 *   apply  --payload <file>  adds the entry to src/data/serverCatalog.json, stores
 *                            the logo (downloaded or a generated monogram) and
 *                            bumps the catalog size in catalogUtils.test.ts.
 *   report --payload <file> --id <id> ...
 *                            aligns transport and auth with what the runner
 *                            observed and writes the pull request body.
 *
 * The payload is re-validated with the same schema the Worker uses, because a
 * dispatch can be sent by anyone holding a token for the repository.
 */
import fs from 'node:fs';
import path from 'node:path';
import assetValidator from './validate-catalog-assets.js';
import {
  CATALOG_SUBMISSION_SCHEMA_URL,
  deriveCatalogId,
  findCatalogDuplicate,
  getSubmissionUrlError,
  type CatalogSubmission,
  type CatalogSubmissionEvidence,
} from '../src/utils/catalogSubmission';
import { validateCatalogSubmission } from '../src/utils/catalogSubmissionSchema';
import type { CatalogAuthType, CatalogServerSeed, CatalogValidationResult } from '../src/types/catalog';

export interface CatalogSubmissionPayload {
  submission_id: string;
  proposed_id?: string;
  submitted_at?: string;
  submission: Omit<CatalogSubmission, '$schema' | 'evidence' | 'contactEmail' | 'turnstileToken'>;
  evidence: CatalogSubmissionEvidence;
  contact_email?: string;
}

export interface SubmissionPaths {
  catalog: string;
  validation: string;
  logos: string;
  catalogSizeTest: string;
}

const projectRoot = path.join(__dirname, '..');

export const DEFAULT_PATHS: SubmissionPaths = {
  catalog: path.join(projectRoot, 'src', 'data', 'serverCatalog.json'),
  validation: path.join(projectRoot, 'src', 'data', 'catalogValidation.json'),
  logos: path.join(projectRoot, 'public', 'server-logos'),
  catalogSizeTest: path.join(projectRoot, 'src', 'utils', 'catalogUtils.test.ts'),
};

const SUBMISSION_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const LOGO_DOWNLOAD_TIMEOUT_MS = 15_000;

const readJson = <T>(file: string): T => JSON.parse(fs.readFileSync(file, 'utf8')) as T;
const writeJson = (file: string, value: unknown) => fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');

/** Re-checks a dispatch payload with the Worker's schema. Throws with every problem found. */
export const parseSubmissionPayload = (value: unknown): CatalogSubmissionPayload => {
  const payload = value as CatalogSubmissionPayload;
  if (!payload || typeof payload !== 'object' || !SUBMISSION_ID.test(String(payload.submission_id))) {
    throw new Error('Payload needs a submission_id generated by the Worker.');
  }
  const validation = validateCatalogSubmission({
    $schema: CATALOG_SUBMISSION_SCHEMA_URL,
    ...payload.submission,
    evidence: payload.evidence,
    ...(payload.contact_email ? { contactEmail: payload.contact_email } : {}),
  });
  if ('errors' in validation) throw new Error(`Submission payload is invalid:\n- ${validation.errors.join('\n- ')}`);
  return payload;
};

const AUTH_TYPES: Record<CatalogSubmissionEvidence['authChallenge'], CatalogAuthType> = {
  none: 'none',
  oauth: 'oauth',
  bearer: 'bearer-token',
  unspecified: 'unknown',
};

const slug = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const escapeXml = (value: string) => value
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const MONOGRAM_COLORS = ['#047857', '#0f766e', '#1d4ed8', '#6d28d9', '#a21caf', '#b45309', '#334155', '#be123c'];

export const monogramInitials = (name: string): string => {
  const words = name.match(/[A-Za-z0-9]+/g) || ['?'];
  const initials = words.length > 1 ? `${words[0][0]}${words[1][0]}` : words[0].slice(0, 2);
  return initials.toUpperCase();
};

/** Same shape as the existing generated-fallback logos in public/server-logos. */
export const generateMonogramSvg = (id: string, name: string): string => {
  const hash = Array.from(id).reduce((total, character) => (total * 31 + character.charCodeAt(0)) >>> 0, 7);
  const color = MONOGRAM_COLORS[hash % MONOGRAM_COLORS.length];
  const initials = monogramInitials(name);
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-labelledby="title">',
    `  <title id="title">${escapeXml(name)} generated fallback monogram</title>`,
    `  <rect width="128" height="128" rx="24" fill="${color}"/>`,
    `  <text x="64" y="${initials.length > 1 ? 75 : 78}" fill="#fff" font-family="Arial, Helvetica, sans-serif" font-size="${initials.length > 1 ? 42 : 52}" font-weight="700" text-anchor="middle">${escapeXml(initials)}</text>`,
    '</svg>',
    '',
  ].join('\n');
};

/** GitHub blob links (the Simple Icons convention) are fetched from raw.githubusercontent.com. */
export const resolveLogoDownloadUrl = (logoUrl: string): string => {
  const url = new URL(logoUrl);
  const blob = url.hostname === 'github.com' && url.pathname.match(/^\/([^/]+)\/([^/]+)\/blob\/(.+)$/);
  return blob ? `https://raw.githubusercontent.com/${blob[1]}/${blob[2]}/${blob[3]}` : url.toString();
};

const simpleIconsVersion = (logoUrl: string): string | undefined => (
  new URL(logoUrl).pathname.match(/\/simple-icons\/simple-icons\/blob\/(\d[^/]*)\//)?.[1]
);

export interface LogoOutcome {
  fields: Pick<CatalogServerSeed, 'logoUrl' | 'logoSourceUrl' | 'logoSourceKind' | 'logoRetrievedAt' | 'logoLicenseNote'>;
  /** Why a submitted logo was replaced by the monogram, if it was. */
  fallbackReason?: string;
}

const fallbackLogo = (id: string, name: string, logos: string, today: string, fallbackReason?: string): LogoOutcome => {
  fs.writeFileSync(path.join(logos, `${id}.svg`), generateMonogramSvg(id, name), 'utf8');
  return {
    fields: {
      logoUrl: `/server-logos/${id}.svg`,
      logoSourceKind: 'generated-fallback',
      logoRetrievedAt: today,
      logoLicenseNote: `Locally generated ${monogramInitials(name)} monogram for a community submission; it is not an official ${name} mark.`,
    },
    ...(fallbackReason ? { fallbackReason } : {}),
  };
};

const readLimited = async (response: Response, limit: number): Promise<Buffer> => {
  const declared = Number(response.headers.get('content-length') || '0');
  if (declared > limit) throw new Error(`is ${declared} bytes; maximum is ${limit}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  if (buffer.byteLength > limit) throw new Error(`is ${buffer.byteLength} bytes; maximum is ${limit}`);
  return buffer;
};

/** Downloads a licensed logo and keeps it only if it passes the catalog asset rules. */
export const storeLogo = async (
  { id, name, submission, logos, today, fetchImpl = fetch }: {
    id: string;
    name: string;
    submission: CatalogSubmissionPayload['submission'];
    logos: string;
    today: string;
    fetchImpl?: typeof fetch;
  }
): Promise<LogoOutcome> => {
  if (submission.logoLicense === 'none' || !submission.logoUrl) return fallbackLogo(id, name, logos, today);

  const sourceUrl = submission.logoUrl;
  let file: string | undefined;
  try {
    const downloadUrl = resolveLogoDownloadUrl(sourceUrl);
    const urlError = getSubmissionUrlError(downloadUrl, 'Logo URL');
    if (urlError) throw new Error(urlError);
    const response = await fetchImpl(downloadUrl, { redirect: 'follow', signal: AbortSignal.timeout(LOGO_DOWNLOAD_TIMEOUT_MS) });
    if (!response.ok) throw new Error(`download returned HTTP ${response.status}`);
    const contentType = (response.headers.get('content-type') || '').toLowerCase();
    const body = await readLimited(response, assetValidator.MAX_LOGO_BYTES);
    const isPng = body.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
    const isSvg = !isPng && (/svg/.test(contentType) || /\.svg$/i.test(new URL(downloadUrl).pathname)) && /<svg[\s>]/i.test(body.toString('utf8'));
    if (!isPng && !isSvg) throw new Error('is neither an SVG nor a PNG');
    const extension = isPng ? 'png' : 'svg';
    file = path.join(logos, `${id}.${extension}`);
    fs.writeFileSync(file, body);
    const errors = assetValidator.validateLogoFile(file, `/server-logos/${id}.${extension}`);
    if (errors.length > 0) throw new Error(errors.join('; '));

    const host = new URL(sourceUrl).hostname;
    const version = submission.logoLicense === 'simple-icons' ? simpleIconsVersion(sourceUrl) : undefined;
    return {
      fields: {
        logoUrl: `/server-logos/${id}.${extension}`,
        logoSourceUrl: sourceUrl,
        logoSourceKind: submission.logoLicense,
        logoRetrievedAt: today,
        logoLicenseNote: submission.logoLicense === 'simple-icons'
          ? `${name} mark from Simple Icons${version ? ` version ${version}` : ''}, as stated by the submitter; trademark rights remain with the owner.`
          : `${name} mark from the publisher's brand asset page on ${host}, as stated by the submitter; trademark rights remain with the publisher.`,
      },
    };
  } catch (error) {
    if (file && fs.existsSync(file)) fs.rmSync(file);
    const reason = `The submitted logo ${error instanceof Error ? error.message : String(error)}`;
    return fallbackLogo(id, name, logos, today, reason);
  }
};

/** Builds the seed without logo fields. */
export const buildCatalogEntry = (
  id: string,
  payload: CatalogSubmissionPayload
): Omit<CatalogServerSeed, 'logoUrl' | 'logoSourceKind' | 'logoRetrievedAt'> => {
  const { submission, evidence } = payload;
  const authType = AUTH_TYPES[evidence.authChallenge];
  const transport = evidence.transport || (/\/sse\/?$/i.test(submission.url) ? 'legacy-sse' : 'streamable-http');
  const browserAccess = evidence.browserAccess === 'unknown' ? undefined : evidence.browserAccess;
  const browserUrl = browserAccess === 'direct' && evidence.validatedUrl && evidence.validatedUrl !== submission.url
    ? evidence.validatedUrl
    : undefined;
  const authTag = authType === 'none' ? 'no-auth' : authType === 'oauth' ? 'oauth' : undefined;
  return {
    id,
    name: submission.name,
    url: submission.url,
    ...(browserUrl ? { browserUrl } : {}),
    ...(browserAccess ? { browserAccess } : {}),
    description: submission.description,
    category: submission.category,
    tags: Array.from(new Set([slug(submission.category), 'community-submission', ...(authTag ? [authTag] : [])])),
    listingSource: { kind: 'community-submission', url: submission.homepageUrl },
    transport,
    requiresOAuth: authType === 'oauth',
    authType,
    homepageUrl: submission.homepageUrl,
  };
};

// Fixed key order so the new entry reads like the hand-written ones.
const SEED_KEY_ORDER = [
  'id', 'name', 'url', 'browserUrl', 'browserAccess', 'description', 'category', 'tags', 'listingSource',
  'transport', 'requiresOAuth', 'authType', 'logoUrl', 'logoSourceUrl', 'logoSourceKind', 'logoRetrievedAt',
  'logoLicenseNote', 'homepageUrl',
];
const orderSeed = (seed: Record<string, unknown>) => Object.fromEntries(
  SEED_KEY_ORDER.filter((key) => seed[key] !== undefined).map((key) => [key, seed[key]])
) as unknown as CatalogServerSeed;

/** The catalog size test pins the number of entries; keep it in step with the new entry. */
export const bumpCatalogSizeTest = (file: string, previous: number, next: number): boolean => {
  if (!fs.existsSync(file)) return false;
  const source = fs.readFileSync(file, 'utf8');
  const updated = source
    .split(`toHaveLength(${previous})`).join(`toHaveLength(${next})`)
    .split(`.size).toBe(${previous})`).join(`.size).toBe(${next})`);
  if (updated === source) return false;
  fs.writeFileSync(file, updated, 'utf8');
  return true;
};

export interface ApplyResult {
  id: string;
  entry: CatalogServerSeed;
  logo: LogoOutcome;
}

export const applySubmission = async (
  payloadValue: unknown,
  { paths = DEFAULT_PATHS, today = new Date().toISOString().slice(0, 10), fetchImpl = fetch }: {
    paths?: SubmissionPaths;
    today?: string;
    fetchImpl?: typeof fetch;
  } = {}
): Promise<ApplyResult> => {
  const payload = parseSubmissionPayload(payloadValue);
  const seeds = readJson<CatalogServerSeed[]>(paths.catalog);
  const duplicate = findCatalogDuplicate(payload.submission.url, seeds);
  if (duplicate) throw new Error(`${payload.submission.url} is already listed as ${duplicate.id}.`);

  const id = deriveCatalogId(payload.submission.url, [
    ...seeds.map((seed) => seed.id),
    // A logo file without an entry would collide with the new one.
    ...fs.readdirSync(paths.logos).map((file) => file.replace(/\.[^.]+$/, '')),
  ]);
  const logo = await storeLogo({ id, name: payload.submission.name, submission: payload.submission, logos: paths.logos, today, fetchImpl });
  const entry = orderSeed({ ...buildCatalogEntry(id, payload), ...logo.fields });
  writeJson(paths.catalog, [...seeds, entry]);
  bumpCatalogSizeTest(paths.catalogSizeTest, seeds.length, seeds.length + 1);
  return { id, entry, logo };
};

/**
 * Applies what the runner observed to the new entry: the validator's transport
 * and auth type replace the browser's claims when the runner saw the server online.
 */
export const reconcileWithValidation = (
  id: string,
  { paths = DEFAULT_PATHS }: { paths?: SubmissionPaths } = {}
): CatalogValidationResult | undefined => {
  const results = fs.existsSync(paths.validation) ? readJson<CatalogValidationResult[]>(paths.validation) : [];
  const result = results.find((entry) => entry.serverId === id);
  if (!result || result.status !== 'online') return result;
  const seeds = readJson<CatalogServerSeed[]>(paths.catalog);
  const seed = seeds.find((entry) => entry.id === id);
  if (!seed) return result;
  if (result.transport === 'streamable-http' || result.transport === 'legacy-sse') seed.transport = result.transport;
  if (result.authType && result.authType !== 'unknown') {
    seed.authType = result.authType;
    seed.requiresOAuth = result.authType === 'oauth';
    seed.tags = seed.tags.filter((tag) => tag !== 'no-auth' && tag !== 'oauth');
    if (result.authType === 'none') seed.tags.push('no-auth');
    if (result.authType === 'oauth') seed.tags.push('oauth');
  }
  writeJson(paths.catalog, seeds);
  return result;
};

/** Escapes text from the submitter so it cannot add markup, links or @mentions to the PR body. */
export const escapeMarkdown = (value: string): string => value
  .replace(/[\\`*_{}[\]()#+!|<>~@]/g, (character) => `\\${character}`)
  .replace(/\r?\n/g, ' ');

const code = (value: string) => `\`${value.replace(/`/g, "'")}\``;

const tail = (file: string | undefined, lines = 40): string => {
  if (!file || !fs.existsSync(file)) return '';
  return fs.readFileSync(file, 'utf8').trimEnd().split('\n').slice(-lines).join('\n').replace(/```/g, "'''");
};

export interface ReportInput {
  payload: CatalogSubmissionPayload;
  id: string;
  validation?: CatalogValidationResult;
  validationOutcome: string;
  validationLog?: string;
  assetsOutcome: string;
  assetsLog?: string;
  logoFallbackReason?: string;
  runUrl?: string;
}

export interface ReportOutput {
  title: string;
  body: string;
  draft: boolean;
}

export const renderPullRequest = (input: ReportInput): ReportOutput => {
  const { payload, id, validation } = input;
  const { submission, evidence } = payload;
  const validationPassed = input.validationOutcome === 'success' && validation?.status === 'online';
  const assetsPassed = input.assetsOutcome === 'success';
  const draft = !validationPassed || !assetsPassed;
  const yesNo = (passed: boolean) => (passed ? 'passed' : '**failed**');

  const lines = [
    `## Catalog submission: ${escapeMarkdown(submission.name)}`,
    '',
    `Submitted through [mcptest.io/submit](https://mcptest.io/submit)${payload.submitted_at ? ` on ${code(payload.submitted_at)}` : ''} as submission ${code(payload.submission_id)}. The submitter confirmed they are authorized to list this server.`,
    '',
    draft
      ? '> [!WARNING]\n> Runner-side checks failed, so this pull request was opened as a draft. See *Runner-side validation* below.'
      : '> [!NOTE]\n> Runner-side validation and the asset checks passed.',
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Catalog id | ${code(id)} |`,
    `| Endpoint | ${code(submission.url)} |`,
    `| Category | ${escapeMarkdown(submission.category)} |`,
    `| Homepage | ${code(submission.homepageUrl)} |`,
    `| Logo | ${submission.logoLicense === 'none' ? 'Generated monogram (no logo submitted)' : `${submission.logoLicense === 'simple-icons' ? 'Simple Icons' : 'Official brand asset'}: ${code(submission.logoUrl || '')}`} |`,
    '',
    ...(input.logoFallbackReason ? [`The submitted logo was not used: ${escapeMarkdown(input.logoFallbackReason)}. A generated monogram was stored instead.`, ''] : []),
    '### Description from the submitter',
    '',
    `> ${escapeMarkdown(submission.description)}`,
    '',
    '### Browser-side evidence',
    '',
    '| Check | Result |',
    '| --- | --- |',
    `| Checked at | ${code(evidence.checkedAt)} |`,
    `| Outcome | ${evidence.outcome === 'mcp' ? 'MCP handshake completed' : 'Authentication challenge'} |`,
    `| Answering endpoint | ${evidence.validatedUrl ? code(evidence.validatedUrl) : 'Not recorded'} |`,
    `| Transport | ${evidence.transport || 'Not negotiated'} |`,
    `| Protocol version | ${evidence.protocolVersion ? code(evidence.protocolVersion) : 'Not negotiated'}${evidence.protocolEra ? ` (${evidence.protocolEra})` : ''} |`,
    `| Auth challenge | ${evidence.authChallenge}${evidence.authStatus ? ` (HTTP ${evidence.authStatus})` : ''} |`,
    `| Browser CORS | ${evidence.browserAccess} |`,
    `| Tools without credentials | ${evidence.toolCount ?? 'Not available'} |`,
    '',
    `${escapeMarkdown(evidence.detail)}`,
    '',
    'This evidence was produced in the submitter\'s browser and cannot be verified on its own. The runner result below is authoritative.',
    '',
    '### Runner-side validation',
    '',
    `- ${code(`npm run validate-catalog -- --only ${id}`)}: ${yesNo(validationPassed)}`,
    ...(validation ? [
      `  - Status ${code(validation.status)}, transport ${code(validation.transport)}, protocol ${code(validation.protocolVersion || validation.protocolEra || 'unknown')}, auth ${code(validation.authType || 'unknown')}${validation.errorCode ? `, error ${code(validation.errorCode)}` : ''}`,
      ...(validation.message ? [`  - ${escapeMarkdown(validation.message)}`] : []),
    ] : ['  - No validation result was recorded.']),
    `- ${code('npm run validate-catalog-assets')}: ${yesNo(assetsPassed)}`,
    '',
    ...[['Validation log', input.validationLog], ['Asset check log', input.assetsLog]]
      .filter(([, file]) => tail(file))
      .flatMap(([label, file]) => ['<details>', `<summary>${label}</summary>`, '', '```text', tail(file), '```', '', '</details>', '']),
    '### Contact',
    '',
    payload.contact_email
      ? `Publisher contact for the maintainer: ${code(payload.contact_email)}. It is not written to the catalog.`
      : 'The submitter did not leave a contact email.',
    '',
    '### Maintainer checklist',
    '',
    '- [ ] The endpoint belongs to the named publisher, and the homepage documents it.',
    '- [ ] The runner reports the server `online`, and the declared `authType` matches what it observed.',
    '- [ ] The name and description are factual, name the authentication method, and contain no marketing copy.',
    '- [ ] The category and tags fit; the generated id reads well (rename the entry and logo file if not).',
    '- [ ] The logo provenance and license note are accurate, or the generated monogram is acceptable.',
    '- [ ] For OAuth servers, add an `oauthRegistration` block if the registration flow is known.',
    '- [ ] CI is green (close and reopen this pull request to run it; bot pull requests do not trigger CI).',
    '',
    '---',
    '',
    `Generated by the catalog submission workflow${input.runUrl ? ` ([run](${input.runUrl}))` : ''}. Process: ${code('docs/catalog-submissions.md')}.`,
    '',
  ];

  return {
    title: `Add ${submission.name.replace(/[\r\n]/g, ' ')} to the catalog (community submission)`,
    body: lines.join('\n'),
    draft,
  };
};
